#!/usr/bin/env sh
# Prints the Homebrew cask for a desktop app release, using the DMG's checksum
# from its SHA256SUMS file. Meant for github.com/qorvyx/homebrew-tap as
# Casks/tmpmail-desktop.rb once the app is out of pre-release; gui-release.yml
# doesn't run it yet.
#
#   scripts/homebrew-cask.sh VERSION SHA256SUMS > tmpmail-desktop.rb
set -eu

[ $# -eq 2 ] || { echo "usage: $0 VERSION SHA256SUMS" >&2; exit 2; }
version=$1
sums=$2
repo=https://github.com/qorvyx/tmpmail

file="tmpmail-desktop-$version-universal.dmg"
sum=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
[ -n "$sum" ] || { echo "no checksum for $file in $sums" >&2; exit 1; }

cat <<EOF2
# Generated by scripts/homebrew-cask.sh in $repo; edits here are overwritten.
cask "tmpmail-desktop" do
  version "$version"
  sha256 "$sum"

  url "$repo/releases/download/gui-v#{version}/tmpmail-desktop-#{version}-universal.dmg"
  name "tmpmail"
  desc "Disposable email with live mail and one-click verification codes"
  homepage "$repo"

  depends_on macos: ">= :catalina"

  app "tmpmail.app"

  # Only the app's own webview data: the inboxes and config.toml are shared
  # with the tmpmail command-line tool.
  zap trash: [
    "~/Library/Application Support/io.github.qorvyx.tmpmail",
    "~/Library/Caches/io.github.qorvyx.tmpmail",
    "~/Library/HTTPStorages/io.github.qorvyx.tmpmail",
    "~/Library/Preferences/io.github.qorvyx.tmpmail.plist",
    "~/Library/Saved Application State/io.github.qorvyx.tmpmail.savedState",
    "~/Library/WebKit/io.github.qorvyx.tmpmail",
  ]

  caveats <<~EOS
    tmpmail isn't notarized by Apple (it is ad-hoc signed), so macOS blocks
    the first start. To allow it once:
      1. Open tmpmail and close the warning.
      2. In System Settings > Privacy & Security, click "Open Anyway"
         next to the message about tmpmail, and enter your password.
      3. Open tmpmail again and confirm.
    Or, if you trust this download:
      xattr -dr com.apple.quarantine "#{appdir}/tmpmail.app"
  EOS
end
EOF2
