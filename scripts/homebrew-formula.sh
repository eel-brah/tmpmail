#!/usr/bin/env sh
# Prints the Homebrew formula for a release, using the archive checksums from
# its SHA256SUMS file. The release workflow pushes the result to
# github.com/qorvyx/homebrew-tap as Formula/tmpmail.rb.
#
#   scripts/homebrew-formula.sh VERSION SHA256SUMS > tmpmail.rb
set -eu

version=$1
sums=$2
repo=https://github.com/qorvyx/tmpmail

sha() {
  file="tmpmail-$version-$1.tar.gz"
  sum=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [ -n "$sum" ] || { echo "no checksum for $file in $sums" >&2; exit 1; }
  echo "$sum"
}

asset() {
  echo "      url \"$repo/releases/download/v$version/tmpmail-$version-$1.tar.gz\""
  echo "      sha256 \"$(sha "$1")\""
}

cat <<EOF
# Generated by scripts/homebrew-formula.sh in $repo; edits here are overwritten.
class Tmpmail < Formula
  desc "Temporary email from the terminal, with provider fallback and OTP waiting"
  homepage "$repo"
  license "GPL-3.0-or-later"

  on_macos do
    on_arm do
$(asset aarch64-apple-darwin)
    end
    on_intel do
$(asset x86_64-apple-darwin)
    end
  end

  on_linux do
    on_arm do
$(asset aarch64-unknown-linux-musl)
    end
    on_intel do
$(asset x86_64-unknown-linux-musl)
    end
  end

  def install
    bin.install "tmpmail"
    generate_completions_from_executable(bin/"tmpmail", "completions")
    system bin/"tmpmail", "man", "--output", buildpath/"man"
    man1.install Dir[buildpath/"man/*.1"]
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/tmpmail --version")
    assert_match "mailtm", shell_output("#{bin}/tmpmail providers")
  end
end
EOF
